package com.seatflow.activity;

import java.time.Clock;
import java.time.LocalDateTime;
import java.util.List;

import com.seatflow.activity.dto.CreateActivityRequest;
import com.seatflow.security.CurrentUser;
import com.seatflow.security.CurrentUserProvider;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import com.seatflow.activity.dto.ActivityResponse;
import com.seatflow.common.BusinessException;
import lombok.RequiredArgsConstructor;

/**
 * Application logic for activities.
 *
 * <p>The repository is injected through the constructor generated by
 * {@code @RequiredArgsConstructor}. Field injection is avoided: constructor
 * injection makes dependencies explicit, keeps fields final and lets tests
 * build the service with a plain constructor call.
 *
 * <p>中文批注：活动业务逻辑与事务边界的所在地。@Transactional 属于这一层，不属于控制器
 * （放在控制器会让事务横跨参数序列化，变成占着数据库连接的长事务）。
 * 依赖通过构造器注入，所以测试可以 new 出对象并传入假仓储与假时钟；字段是 final，构造后不可变。
 * 时间统一取自注入的 Clock，并且每次调用只取一次"现在"，保证同一份响应里所有行基于同一时刻判断，
 * 否则边界上的两行数据可能自相矛盾。
 */
@Service
@RequiredArgsConstructor
public class ActivityService {

    private final ActivityRepository activityRepository;
    private final Clock clock;
    private final CurrentUserProvider currentUserProvider;

    @Transactional(readOnly = true)
    public List<ActivityResponse> listPublishedActivities() {
        LocalDateTime now = LocalDateTime.now(clock);
        return activityRepository.findByStatusOrderByRegistrationStartAsc(ActivityStatus.PUBLISHED)
                .stream()
                .map(activity -> ActivityResponse.from(activity, now))
                .toList();
    }

    @Transactional(readOnly = true)
    public ActivityResponse getActivity(Long id) {
        LocalDateTime now = LocalDateTime.now(clock);
        return activityRepository.findById(id)
                .map(activity -> ActivityResponse.from(activity, now))
                .orElseThrow(() -> BusinessException.notFound("activity not found: " + id));
    }

    @Transactional
    public ActivityResponse createActivity(CreateActivityRequest request) {
        CurrentUser currentUser = currentUserProvider.require();
        if (!currentUser.canCreateActivity()) {
            throw new BusinessException(403, "only organizer can create activity");
        }
        Activity activity = new Activity();
        activity.setOrganizerId(currentUser.id());
        activity.setTitle(request.title());
        activity.setDescription(request.description());
        activity.setLocation(request.location());
        activity.setCapacity(request.capacity());
        activity.setRegisteredCount(0);
        activity.setRegistrationStart(request.registrationStart());
        activity.setRegistrationEnd(request.registrationEnd());
        activity.setStatus(ActivityStatus.DRAFT);
        Activity saved = activityRepository.save(activity);
        return ActivityResponse.from(saved, LocalDateTime.now(clock));
    }
}
